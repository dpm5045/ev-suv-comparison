#!/usr/bin/env node
/**
 * Generates lib/ev-data.types.ts from the schema's field catalog, so the
 * TypeScript row type can't drift from the build-time contract.
 *
 *   node scripts/schema/gen-types.mjs          # write the file
 *   node scripts/schema/gen-types.mjs --check  # fail if the committed file is stale (CI)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { FIELDS } from './ev-data.schema.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const OUT = join(ROOT, 'lib/ev-data.types.ts')

const tsType = (spec) => {
  const parts = []
  if (spec.type === 'enum') parts.push(...spec.values.map((v) => JSON.stringify(v)))
  else parts.push(spec.type === 'integer' ? 'number' : spec.type)
  for (const s of spec.sentinels ?? []) parts.push(JSON.stringify(s))
  if (spec.nullable) parts.push('null')
  return parts.join(' | ')
}

export function render() {
  const lines = [
    '// GENERATED by scripts/schema/gen-types.mjs from scripts/schema/ev-data.schema.mjs.',
    '// Do not edit by hand: change the schema and re-run the generator (CI checks it is current).',
    '',
    '/** One stored row of lib/ev-data.json `details` (schema_version 2), before load-time enrichment. */',
    'export interface RawDetailRow {',
    ...Object.entries(FIELDS).map(([k, spec]) => `  ${k}: ${tsType(spec)}`),
    '}',
    '',
  ]
  return lines.join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render()
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
    if (cur !== text) {
      console.error('lib/ev-data.types.ts is out of date with the schema: run node scripts/schema/gen-types.mjs')
      process.exit(1)
    }
    console.log('lib/ev-data.types.ts is current')
  } else {
    writeFileSync(OUT, text)
    console.log('wrote lib/ev-data.types.ts')
  }
}
